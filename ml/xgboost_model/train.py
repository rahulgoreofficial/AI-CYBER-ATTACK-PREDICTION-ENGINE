# ISOLATION FOREST (M4.3)
# ==============================================================================

def train_isolation_forest(
    X_train: np.ndarray,
    feature_names: list[str],
    config: dict | None = None,
) -> object:
    """
    Train Isolation Forest for anomaly detection.

    Returns anomaly scores in [-1, 1] where more negative = more anomalous.
    We normalize to [0, 1] where higher = more anomalous.
    """
    from sklearn.ensemble import IsolationForest

    if config is None:
        config = MODEL_CONFIG.get("isolation_forest", {})

    model = IsolationForest(
        n_estimators=config.get("n_estimators", 100),
        contamination=config.get("contamination", "auto"),
        random_state=RANDOM_SEED,
        n_jobs=-1,
    )

    model.fit(X_train)
    print("[if] Isolation Forest trained")

    return model


def get_anomaly_scores(if_model, X: np.ndarray) -> np.ndarray:
    """
    Get normalized anomaly scores from Isolation Forest.

    Returns:
        Scores in [0, 1] where higher = more anomalous.
    """
    # decision_function returns: higher = more normal, lower = more anomalous
    raw_scores = if_model.decision_function(X)

    # Invert and normalize to [0, 1]: more anomalous = higher
    scores = -raw_scores
    s_min, s_max = scores.min(), scores.max()
    if s_max > s_min:
        scores = (scores - s_min) / (s_max - s_min)
    else:
        scores = np.zeros_like(scores)

    return scores


# ==============================================================================
# DYNAMIC RISK ENGINE (M4.4)
# ==============================================================================

def compute_dynamic_risk(
    df: pd.DataFrame,
    attack_probs: np.ndarray,
    anomaly_scores: np.ndarray | None = None,
    weights: dict | None = None,
) -> pd.DataFrame:
    """
    M4.4 — Dynamic Risk Engine.

    Risk = w1*attack_prob + w2*anomaly + w3*vulnerability
         + w4*topology_exposure + w5*criticality + w6*recency

    Args:
        df: Feature DataFrame with device metadata.
        attack_probs: Model-predicted attack probabilities.
        anomaly_scores: Isolation Forest anomaly scores (optional).
        weights: Risk component weights (default: equal).

    Returns:
        DataFrame with risk scores and rankings.
    """
    from ml.config import RISK_WEIGHTS

    if weights is None:
        weights = RISK_WEIGHTS

    n = len(df)

    # Component 1: Attack probability (from ML model)
    c_attack = attack_probs

    # Component 2: Anomaly score
    if anomaly_scores is not None:
        c_anomaly = anomaly_scores
    else:
        c_anomaly = np.zeros(n)

    # Component 3: Vulnerability score
    c_vuln = df["device_vulnerability"].values if "device_vulnerability" in df.columns else np.full(n, 0.5)

    # Component 4: Topology exposure (betweenness centrality as proxy)
    if "betweenness_centrality" in df.columns:
        bc = df["betweenness_centrality"].values
        bc_max = max(bc.max(), 1e-10)
        c_topo = bc / bc_max
    else:
        c_topo = np.full(n, 0.5)

    # Component 5: Asset criticality
    c_crit = df["device_criticality"].values if "device_criticality" in df.columns else np.full(n, 0.5)

    # Component 6: Recency (how recently the device had attack-adjacent activity)
    if "neighbor_attack_count" in df.columns:
        nac = df["neighbor_attack_count"].values
        nac_max = max(nac.max(), 1e-10)
        c_recency = nac / nac_max
    else:
        c_recency = np.zeros(n)

    # Weighted combination
    risk = (
        weights["attack_probability"] * c_attack
        + weights["anomaly_score"] * c_anomaly
        + weights["vulnerability_score"] * c_vuln
        + weights["topology_exposure"] * c_topo
        + weights["asset_criticality"] * c_crit
        + weights["recency_score"] * c_recency
    )

    # Build result DataFrame
    risk_df = pd.DataFrame({
        "window_id": df["window_id"].values,
        "device_id": df["device_id"].values,
        "attack_probability": c_attack,
        "anomaly_score": c_anomaly,
        "vulnerability_score": c_vuln,
        "topology_exposure": c_topo,
        "asset_criticality": c_crit,
        "recency_score": c_recency,
        "dynamic_risk_score": risk,
    })

    # Per-window ranking
    risk_df["risk_rank"] = risk_df.groupby("window_id")["dynamic_risk_score"].rank(
        ascending=False, method="min"
    ).astype(int)

    return risk_df


