def load_feature_matrix(day: str = "wednesday") -> pd.DataFrame:
    """Load the ML feature matrix generated by feature_combiner."""
    path = PATHS["data_processed"] / f"ml_feature_matrix_{day}.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"Feature matrix not found: {path}\n"
            f"Run: python -m ml.feature_engineering.feature_combiner --day {day}"
        )
    df = pd.read_csv(path, low_memory=False)
    print(f"[xgb] Loaded feature matrix: {df.shape[0]:,} rows x {df.shape[1]} cols")
    return df


def prepare_features(
    df: pd.DataFrame,
) -> tuple[pd.DataFrame, list[str], str]:
    """
    Separate features, target, and metadata columns.

    Returns:
        (df, feature_columns, target_column)
    """
    # Target column
    target_col = "is_future_target"

    # Metadata / non-feature columns
    exclude_cols = {
        "window_id", "device_id",
        "is_future_target", "target_attack_count",
        "target_attack_types", "earliest_target_window",
    }

    # Feature columns = everything numeric that's not excluded
    feature_cols = [
        c for c in df.columns
        if c not in exclude_cols and df[c].dtype in [np.float64, np.int64, np.float32, np.int32, np.uint8, bool]
    ]

    print(f"[xgb] Features: {len(feature_cols)}, Target: {target_col}")
    return df, feature_cols, target_col


def temporal_split(
    df: pd.DataFrame,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Split by time window — earlier windows train, later windows test.
    No shuffling to prevent temporal leakage.
    """
    all_windows = sorted(df["window_id"].unique())
    n = len(all_windows)

    train_end = int(n * train_ratio)
    val_end = int(n * (train_ratio + val_ratio))

    train_windows = set(all_windows[:train_end])
    val_windows = set(all_windows[train_end:val_end])
    test_windows = set(all_windows[val_end:])

    train = df[df["window_id"].isin(train_windows)].copy()
    val = df[df["window_id"].isin(val_windows)].copy()
    test = df[df["window_id"].isin(test_windows)].copy()

    for name, split in [("Train", train), ("Val", val), ("Test", test)]:
        pos = split["is_future_target"].sum()
        total = len(split)
        print(f"[xgb] {name}: {total:,} samples, {pos:.0f} positive "
              f"({pos/max(total,1)*100:.1f}%)")

    return train, val, test


# ==============================================================================
# HEURISTIC BASELINE (M4.1)
# ==============================================================================

def heuristic_baseline(
    df: pd.DataFrame,
    feature_cols: list[str],
) -> np.ndarray:
    """
    M4.1 — Heuristic baseline: score = degree x criticality x (1 + neighbor_attack_count).

    No ML — pure graph/topology heuristic.
    Purpose: sanity check; if ML can't beat this, something is wrong.
    """
    degree = df["degree"].values if "degree" in df.columns else np.ones(len(df))
    crit = df["device_criticality"].values if "device_criticality" in df.columns else np.ones(len(df))
    nac = df["neighbor_attack_count"].values if "neighbor_attack_count" in df.columns else np.zeros(len(df))

    # Normalize each component to [0, 1]
    degree_norm = degree / max(degree.max(), 1)
    crit_norm = crit  # already [0, 1]
    nac_norm = nac / max(nac.max(), 1)

    scores = degree_norm * crit_norm * (1 + nac_norm)

    # Normalize to [0, 1]
    score_max = scores.max()
    if score_max > 0:
        scores = scores / score_max

    return scores


# ==============================================================================
# XGBOOST TRAINING (M4.2)
# ==============================================================================

def train_xgboost(
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_val: np.ndarray,
    y_val: np.ndarray,
    feature_names: list[str],
    config: dict | None = None,
) -> xgb.XGBClassifier:
    """
    Train XGBoost with class imbalance handling and early stopping.

    Returns:
        Trained XGBClassifier.
    """
    if config is None:
        config = MODEL_CONFIG["xgboost"].copy()

    # Calculate scale_pos_weight for class imbalance
    n_neg = (y_train == 0).sum()
    n_pos = max((y_train == 1).sum(), 1)
    spw = n_neg / n_pos
    config["scale_pos_weight"] = spw
    print(f"[xgb] scale_pos_weight = {spw:.1f} (neg/pos ratio)")

    model = xgb.XGBClassifier(
        n_estimators=config.get("n_estimators", 200),
        max_depth=config.get("max_depth", 6),
        learning_rate=config.get("learning_rate", 0.1),
        subsample=config.get("subsample", 0.8),
        colsample_bytree=config.get("colsample_bytree", 0.8),
        min_child_weight=config.get("min_child_weight", 5),
        scale_pos_weight=spw,
        eval_metric="logloss",
        random_state=RANDOM_SEED,
        n_jobs=-1,
        use_label_encoder=False,
        early_stopping_rounds=20,
    )

    model.fit(
        X_train, y_train,
        eval_set=[(X_val, y_val)],
        verbose=False,
    )

    best_iter = model.best_iteration
    best_score = model.best_score
    print(f"[xgb] Training complete: best_iteration={best_iter}, "
          f"best_logloss={best_score:.6f}")

    return model


def get_feature_importance(
    model: xgb.XGBClassifier,
    feature_names: list[str],
    top_n: int = 20,
) -> pd.DataFrame:
    """
    Extract and display top feature importances.

    Returns:
        DataFrame with feature names and importance scores.
    """
    importances = model.feature_importances_
    imp_df = pd.DataFrame({
        "feature": feature_names,
        "importance": importances,
    }).sort_values("importance", ascending=False)

    print(f"\n  --- Top {top_n} Feature Importances ---")
    for _, row in imp_df.head(top_n).iterrows():
        bar = "#" * int(row["importance"] * 100)
        print(f"  {row['feature']:<40s} {row['importance']:.4f} {bar}")

    return imp_df


