def train_and_evaluate(
    day: str = "wednesday",
    run_heuristic: bool = True,
    run_xgboost: bool = True,
    run_isolation_forest: bool = True,
    run_risk_engine: bool = True,
    save_models: bool = True,
    verbose: bool = True,
) -> dict:
    """
    Full Phase 4 pipeline: train and evaluate all baseline models.

    Stages:
    1. Heuristic baseline (degree x criticality x neighbor_attacks)
    2. XGBoost on combined features
    3. XGBoost + Isolation Forest anomaly scores
    4. Dynamic risk engine

    Returns:
        Dictionary with all results and model comparison.
    """
    print(f"\n{'='*70}")
    print(f"PHASE 4 -- BASELINE MODELS ({day.upper()})")
    print(f"{'='*70}")

    # ── Load & prepare data ──
    df = load_feature_matrix(day)
    df, feature_cols, target_col = prepare_features(df)
    train_df, val_df, test_df = temporal_split(df)

    X_train = train_df[feature_cols].values
    y_train = train_df[target_col].values
    X_val = val_df[feature_cols].values
    y_val = val_df[target_col].values
    X_test = test_df[feature_cols].values
    y_test = test_df[target_col].values

    all_results = []

    # ══════════════════════════════════════════════════════════
    # M4.1 — Heuristic Baseline
    # ══════════════════════════════════════════════════════════
    if run_heuristic:
        print(f"\n{'-'*50}")
        print("M4.1 -- Heuristic Baseline")
        print(f"{'-'*50}")

        heuristic_scores = heuristic_baseline(test_df, feature_cols)
        heuristic_results = evaluate_predictions(
            y_test, heuristic_scores,
            test_df["device_id"].values,
            test_df["window_id"].values,
            model_name="Heuristic",
            verbose=verbose,
        )
        all_results.append(heuristic_results)

    # ══════════════════════════════════════════════════════════
    # M4.2 — XGBoost Baseline
    # ══════════════════════════════════════════════════════════
    xgb_model = None
    if run_xgboost:
        print(f"\n{'-'*50}")
        print("M4.2 -- XGBoost Baseline")
        print(f"{'-'*50}")

        xgb_model = train_xgboost(
            X_train, y_train, X_val, y_val, feature_cols
        )

        # Feature importance
        imp_df = get_feature_importance(xgb_model, feature_cols, top_n=15)

        # Predict on test set
        xgb_probs = xgb_model.predict_proba(X_test)[:, 1]

        xgb_results = evaluate_predictions(
            y_test, xgb_probs,
            test_df["device_id"].values,
            test_df["window_id"].values,
            model_name="XGBoost",
            verbose=verbose,
        )
        all_results.append(xgb_results)

        if save_models:
            model_path = PATHS["models"] / "xgboost_baseline.pkl"
            model_path.parent.mkdir(parents=True, exist_ok=True)
            joblib.dump(xgb_model, model_path)
            print(f"[xgb] Model saved: {model_path}")

            # Save feature importance
            imp_path = PATHS["experiments"] / f"xgboost_feature_importance_{day}.csv"
            imp_path.parent.mkdir(parents=True, exist_ok=True)
            imp_df.to_csv(imp_path, index=False)

    # ══════════════════════════════════════════════════════════
    # M4.3 — Isolation Forest + XGBoost
    # ══════════════════════════════════════════════════════════
    if_model = None
    if run_isolation_forest and run_xgboost:
        print(f"\n{'-'*50}")
        print("M4.3 -- XGBoost + Isolation Forest")
        print(f"{'-'*50}")

        # Train IF on training data
        if_model = train_isolation_forest(X_train, feature_cols)

        # Get anomaly scores for all splits
        anomaly_train = get_anomaly_scores(if_model, X_train)
        anomaly_val = get_anomaly_scores(if_model, X_val)
        anomaly_test = get_anomaly_scores(if_model, X_test)

        print(f"[if] Anomaly scores -- train: mean={anomaly_train.mean():.4f}, "
              f"test: mean={anomaly_test.mean():.4f}")

        # Augment features with anomaly score
        X_train_aug = np.column_stack([X_train, anomaly_train])
        X_val_aug = np.column_stack([X_val, anomaly_val])
        X_test_aug = np.column_stack([X_test, anomaly_test])
        feature_cols_aug = feature_cols + ["anomaly_score_if"]

        # Train XGBoost with anomaly feature
        xgb_if_model = train_xgboost(
            X_train_aug, y_train, X_val_aug, y_val, feature_cols_aug
        )

        # Predict
        xgb_if_probs = xgb_if_model.predict_proba(X_test_aug)[:, 1]

        xgb_if_results = evaluate_predictions(
            y_test, xgb_if_probs,
            test_df["device_id"].values,
            test_df["window_id"].values,
            model_name="XGBoost + IF",
            verbose=verbose,
        )
        all_results.append(xgb_if_results)

        # Feature importance for augmented model
        get_feature_importance(xgb_if_model, feature_cols_aug, top_n=15)

        if save_models:
            model_path = PATHS["models"] / "isolation_forest.pkl"
            joblib.dump(if_model, model_path)
            print(f"[if] Model saved: {model_path}")

            model_path = PATHS["models"] / "xgboost_with_if.pkl"
            joblib.dump(xgb_if_model, model_path)
            print(f"[xgb+if] Model saved: {model_path}")

    # ══════════════════════════════════════════════════════════
    # M4.4 — Dynamic Risk Engine
    # ══════════════════════════════════════════════════════════
    if run_risk_engine and xgb_model is not None:
        print(f"\n{'-'*50}")
        print("M4.4 -- Dynamic Risk Engine")
        print(f"{'-'*50}")

        # Use the best model's predictions
        if if_model is not None:
            best_probs = xgb_if_probs
            best_anomaly = anomaly_test
        else:
            best_probs = xgb_probs
            best_anomaly = None

        risk_df = compute_dynamic_risk(
            test_df, best_probs, best_anomaly
        )

        # Evaluate risk-based ranking
        risk_results = evaluate_predictions(
            y_test, risk_df["dynamic_risk_score"].values,
            test_df["device_id"].values,
            test_df["window_id"].values,
            model_name="Dynamic Risk",
            verbose=verbose,
        )
        all_results.append(risk_results)

        # Show top-risk devices per window (sample)
        sample_windows = sorted(risk_df["window_id"].unique())[:3]
        print(f"\n  --- Sample Risk Rankings ---")
        for wid in sample_windows:
            w_risk = risk_df[risk_df["window_id"] == wid].sort_values(
                "risk_rank"
            ).head(5)
            print(f"\n  Window {wid}:")
            for _, row in w_risk.iterrows():
                actual = test_df[
                    (test_df["window_id"] == wid) &
                    (test_df["device_id"] == row["device_id"])
                ]["is_future_target"].values
                actual_str = " [ACTUAL TARGET]" if (len(actual) > 0 and actual[0] == 1) else ""
                print(f"    Rank {row['risk_rank']:.0f}: {row['device_id']:<20s} "
                      f"risk={row['dynamic_risk_score']:.4f} "
                      f"atk_prob={row['attack_probability']:.4f}{actual_str}")

        # Save risk scores
        if save_models:
            risk_path = PATHS["experiments"] / f"risk_scores_{day}.csv"
            risk_df.to_csv(risk_path, index=False)
            print(f"\n[risk] Saved risk scores: {risk_path}")

    # ══════════════════════════════════════════════════════════
    # COMPARISON TABLE
    # ══════════════════════════════════════════════════════════
    if len(all_results) > 1:
        print_comparison_table(all_results)

    # Save comparison
    if save_models and all_results:
        comp_path = PATHS["experiments"] / f"model_comparison_{day}.json"
        comp_path.parent.mkdir(parents=True, exist_ok=True)
        with open(comp_path, "w") as f:
            json.dump(all_results, f, indent=2)
        print(f"[results] Saved comparison: {comp_path}")

    return {
        "all_results": all_results,
        "xgb_model": xgb_model,
        "if_model": if_model,
    }


