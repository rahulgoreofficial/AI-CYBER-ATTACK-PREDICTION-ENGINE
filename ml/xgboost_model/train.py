"""
XGBoost Next-Target Prediction Model — Train, predict, and evaluate.
======================================================================

Trains an XGBoost classifier on the combined feature matrix to predict
which device will be the next attack target.

Includes:
- Temporal train/val/test splitting (no data leakage)
- Class imbalance handling via scale_pos_weight
- Feature importance analysis
- Integration with ranking metrics (Top-K, MRR, PR-AUC)

Usage:
    from ml.xgboost_model.train import train_and_evaluate
    results = train_and_evaluate()

    # Or CLI:
    python -m ml.xgboost_model.train --day wednesday
"""

